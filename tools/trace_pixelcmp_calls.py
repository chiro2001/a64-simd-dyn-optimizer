#!/usr/bin/env python3
"""Count real calls to the motion-estimation pixelcmp slots (round-0022
P1 primitive tracing): pu[].sad/sad_x3/sad_x4/satd/pixelavg_pp, cu[].
sa8d and chroma pu satd on the target 920B during a real encode.

Usage:
  python3 tools/trace_pixelcmp_calls.py [outdir] [--cxx ...]
Outputs (default build/trace-pixelcmp):
  pixel_rec.cpp / pixel_rec.o
  x265-dynopt-pixel-trace.patch
"""

import argparse
import difflib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PU_SIZES = [
    "LUMA_4x4", "LUMA_8x4", "LUMA_8x8", "LUMA_4x8", "LUMA_16x8",
    "LUMA_8x16", "LUMA_16x16", "LUMA_16x32", "LUMA_32x16",
    "LUMA_32x32", "LUMA_32x64", "LUMA_64x32", "LUMA_64x64",
]


def gen_src():
    L = []
    L.append("""\
// Generated by tools/trace_pixelcmp_calls.py -- do not edit.
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include "common/primitives.h"

using namespace X265_NS;

static volatile uint64_t g_cnt[256];

static void pixel_trace_dump()
{
    fprintf(stderr, "pixeltrace begin\\n");
    for (int i = 0; i < 256; i++)
        if (g_cnt[i])
            fprintf(stderr, "pixeltrace %d %llu\\n", i,
                    (unsigned long long)g_cnt[i]);
    fprintf(stderr, "pixeltrace end\\n");
}

""")
    L.append("""\
struct DumpReg { DumpReg() { std::atexit(pixel_trace_dump); } };
static DumpReg g_dump_reg;

""")
    # slot ids: 0..12 pu.sad, 13..25 pu.sad_x3, 26..38 pu.sad_x4,
    # 39..51 pu.satd, 52..90 pu.pixelavg_pp[3], 91..95 cu sa8d,
    # 96..108 chroma I420 satd, 109..121 I422, 122..134 I444.
    pu = {}
    for i, name in enumerate(PU_SIZES):
        pu[name] = i
    ids = {"sad": {}, "x3": {}, "x4": {}, "satd": {}, "avg": {},
           "sa8d": {}, "c420": {}, "c422": {}, "c444": {}}
    for name in PU_SIZES:
        ids["sad"][name] = pu[name]
        ids["x3"][name] = 13 + pu[name]
        ids["x4"][name] = 26 + pu[name]
        ids["satd"][name] = 39 + pu[name]
        for a in range(3):
            ids["avg"][(name, a)] = 52 + pu[name] * 3 + a
    for b, base in (("BLOCK_4x4", 91), ("BLOCK_8x8", 92),
                    ("BLOCK_16x16", 93), ("BLOCK_32x32", 94),
                    ("BLOCK_64x64", 95)):
        ids["sa8d"][b] = base
    for csp, base in (("X265_CSP_I420", 96), ("X265_CSP_I422", 109),
                      ("X265_CSP_I444", 122)):
        for name in PU_SIZES:
            ids["c" + csp[-3:]][name] = base + pu[name]

    # Wrappers: save originals, install counting wrappers.
    L.append("extern \"C\" void dynopt_pixel_trace_wrap_all(void);\n\n")
    decls = []
    for name in PU_SIZES:
        decls.append("static pixelcmp_t g_o_sad_%s;" % name)
        decls.append("static pixelcmp_x3_t g_o_x3_%s;" % name)
        decls.append("static pixelcmp_x4_t g_o_x4_%s;" % name)
        decls.append("static pixelcmp_t g_o_satd_%s;" % name)
        for a in range(3):
            decls.append("static pixelavg_pp_t g_o_avg_%s_%d;" % (name, a))
    for b in ("BLOCK_4x4", "BLOCK_8x8", "BLOCK_16x16", "BLOCK_32x32",
              "BLOCK_64x64"):
        decls.append("static pixelcmp_t g_o_sa8d_%s;" % b)
    for csp in ("I420", "I422", "I444"):
        for name in PU_SIZES:
            decls.append("static pixelcmp_t g_o_csatd_%s_%s;" % (csp, name))
    L.append("\n".join(decls) + "\n\n")

    wrappers = []
    for name in PU_SIZES:
        sid = ids["sad"][name]
        wrappers.append("""\
static int w_sad_%(n)s(const pixel* a, intptr_t sa, const pixel* b,
                       intptr_t sb)
{
    const int r = g_o_sad_%(n)s(a, sa, b, sb);
    g_cnt[%(id)d]++;
    return r;
}
""" % {"n": name, "id": sid})
        wrappers.append("""\
static void w_x3_%(n)s(const pixel* fenc, const pixel* fref0,
                       const pixel* fref1, const pixel* fref2,
                       intptr_t frefstride, int32_t* res)
{
    g_o_x3_%(n)s(fenc, fref0, fref1, fref2, frefstride, res);
    g_cnt[%(id)d]++;
}
""" % {"n": name, "id": ids["x3"][name]})
        wrappers.append("""\
static void w_x4_%(n)s(const pixel* fenc, const pixel* fref0,
                       const pixel* fref1, const pixel* fref2,
                       const pixel* fref3, intptr_t frefstride,
                       int32_t* res)
{
    g_o_x4_%(n)s(fenc, fref0, fref1, fref2, fref3, frefstride, res);
    g_cnt[%(id)d]++;
}
""" % {"n": name, "id": ids["x4"][name]})
        wrappers.append("""\
static int w_satd_%(n)s(const pixel* a, intptr_t sa, const pixel* b,
                        intptr_t sb)
{
    const int r = g_o_satd_%(n)s(a, sa, b, sb);
    g_cnt[%(id)d]++;
    return r;
}
""" % {"n": name, "id": ids["satd"][name]})
        for a in range(3):
            wrappers.append("""\
static void w_avg_%(n)s_%(a)d(pixel* dst, intptr_t dstride,
                             const pixel* s0, intptr_t ss0,
                             const pixel* s1, intptr_t ss1, int weight)
{
    g_o_avg_%(n)s_%(a)d(dst, dstride, s0, ss0, s1, ss1, weight);
    g_cnt[%(id)d]++;
}
""" % {"n": name, "a": a, "id": ids["avg"][(name, a)]})
    for b in ("BLOCK_4x4", "BLOCK_8x8", "BLOCK_16x16", "BLOCK_32x32",
              "BLOCK_64x64"):
        wrappers.append("""\
static int w_sa8d_%(b)s(const pixel* a, intptr_t sa, const pixel* b2,
                        intptr_t sb)
{
    const int r = g_o_sa8d_%(b)s(a, sa, b2, sb);
    g_cnt[%(id)d]++;
    return r;
}
""" % {"b": b, "id": ids["sa8d"][b]})
    for csp, tag in (("X265_CSP_I420", "I420"), ("X265_CSP_I422", "I422"),
                     ("X265_CSP_I444", "I444")):
        for name in PU_SIZES:
            wrappers.append("""\
static int w_csatd_%(c)s_%(n)s(const pixel* a, intptr_t sa, const pixel* b,
                               intptr_t sb)
{
    const int r = g_o_csatd_%(c)s_%(n)s(a, sa, b, sb);
    g_cnt[%(id)d]++;
    return r;
}
""" % {"c": tag, "n": name, "id": ids["c" + tag[1:]][name]})
    L.append("\n".join(wrappers))
    L.append("""
extern "C" void dynopt_pixel_trace_wrap_all(void)
{
""")
    assigns = []
    for name in PU_SIZES:
        e = "primitives.pu[%s]" % name
        assigns.append("g_o_sad_%s = %s.sad; %s.sad = w_sad_%s;"
                       % (name, e, e, name))
        assigns.append("g_o_x3_%s = %s.sad_x3; %s.sad_x3 = w_x3_%s;"
                       % (name, e, e, name))
        assigns.append("g_o_x4_%s = %s.sad_x4; %s.sad_x4 = w_x4_%s;"
                       % (name, e, e, name))
        assigns.append("g_o_satd_%s = %s.satd; %s.satd = w_satd_%s;"
                       % (name, e, e, name))
        for a in range(3):
            assigns.append(
                "g_o_avg_%s_%d = %s.pixelavg_pp[%d];"
                " %s.pixelavg_pp[%d] = w_avg_%s_%d;"
                % (name, a, e, a, e, a, name, a))
    for b in ("BLOCK_4x4", "BLOCK_8x8", "BLOCK_16x16", "BLOCK_32x32",
              "BLOCK_64x64"):
        assigns.append("g_o_sa8d_%s = primitives.cu[%s].sa8d;"
                       " primitives.cu[%s].sa8d = w_sa8d_%s;"
                       % (b, b, b, b))
    for csp, tag in (("X265_CSP_I420", "I420"), ("X265_CSP_I422", "I422"),
                     ("X265_CSP_I444", "I444")):
        for name in PU_SIZES:
            assigns.append(
                "g_o_csatd_%s_%s = primitives.chroma[%s].pu[%s].satd;"
                " primitives.chroma[%s].pu[%s].satd = w_csatd_%s_%s;"
                % (tag, name, csp, name, csp, name, tag, name))
    L.append("\n    ".join(assigns))
    L.append("\n}\n")
    return "\n".join(L)


def write_patch(outdir):
    prim = os.path.join(ROOT, "third_party/x265/source/common",
                        "primitives.cpp")
    src = open(prim).read().splitlines()
    mod = list(src)
    for i, line in enumerate(mod):
        if line.strip() == "namespace X265_NS {" and \
                mod[i + 1].strip().startswith("// x265 private namespace"):
            mod.insert(i + 2,
                       'extern "C" void dynopt_pixel_trace_wrap_all();')
            break
    for i, line in enumerate(mod):
        if line.strip() == "setupAliasPrimitives(primitives);":
            mod.insert(i + 1, "        dynopt_pixel_trace_wrap_all();")
            break
    diff = difflib.unified_diff(
        src, mod,
        fromfile="a/source/common/primitives.cpp",
        tofile="b/source/common/primitives.cpp", lineterm="")
    path = os.path.join(outdir, "x265-dynopt-pixel-trace.patch")
    with open(path, "w") as f:
        f.write("\n".join(diff) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir", nargs="?", default="build/trace-pixelcmp")
    ap.add_argument("--cxx", default="aarch64-linux-gnu-g++")
    args = ap.parse_args()
    outdir = os.path.join(ROOT, args.outdir)
    os.makedirs(outdir, exist_ok=True)
    src_path = os.path.join(outdir, "pixel_rec.cpp")
    obj_path = os.path.join(outdir, "pixel_rec.o")
    with open(src_path, "w") as f:
        f.write(gen_src())
    r = subprocess.run(
        [args.cxx, "-O2", "-fPIC", "-std=c++11", "-DX265_NS=x265",
         "-DX265_DEPTH=8", "-DHIGH_BIT_DEPTH=0",
         "-I", os.path.join(ROOT, "third_party/x265/source"),
         "-I", os.path.join(ROOT, "third_party/x265/source/common"),
         "-I", os.path.join(ROOT, "build/x265-8-cross-make"),
         "-c", src_path, "-o", obj_path],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode != 0:
        sys.exit("pixel_rec compile failed:\n" + r.stdout[-3000:])
    patch = write_patch(outdir)
    print("wrote %s" % src_path)
    print("wrote %s" % patch)
    print("wrote %s" % obj_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
