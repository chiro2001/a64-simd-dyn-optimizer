#!/usr/bin/env python3
"""Parameterized SVE2 (VL=256) emitter for SA8D 8x8, manifest-driven.

Open-source x265 sa8d8_sve2 processes one 8-pixel row per 128-bit
operation (24 CADD + 16 TBL for the per-row Hadamard stages). At VL=256
two rows fit per 16-lane register, so the same CADD/TBL stages process
two rows per instruction (pack=2): 12 CADD + 8 TBL; rows are extracted
afterwards (low half free via the NEON bridge, high half one TBL) and
the upstream row-combine/reduction is reused verbatim.

Correctness contract: bit-exact with x265's scalar SA8D reference
(abs-sum of 8x8 Hadamard diff, (sum+1)>>1).
"""


def emit(func_name="dynopt_sa8d_8x8_sve2", pack=2):
    if pack == 1:
        return emit_single(func_name)
    return emit_pair(func_name)


def emit_pair(func_name):
    return """\
// Generated by tools/emit_sa8d_sve2_shared.py -- do not edit by hand.
// Two-row-per-register SA8D 8x8 (VL=256), upstream-exact combine.
#include <arm_sve.h>
#include <arm_neon.h>
#include <arm_neon_sve_bridge.h>

namespace {

static inline uint64x2_t udotq_u16(uint64x2_t acc, uint16x8_t a, uint16x8_t b)
{
    return svget_neonq_u64(svdot_u64(
        svset_neonq_u64(svundef_u64(), acc),
        svset_neonq_u16(svundef_u16(), a),
        svset_neonq_u16(svundef_u16(), b)));
}

static inline void sumsubq_s16(int16x8_t *sum, int16x8_t *sub,
                               const int16x8_t a, const int16x8_t b)
{
    *sum = vaddq_s16(a, b);
    *sub = vsubq_s16(a, b);
}

static inline void abssumsubq_s16(int16x8_t *sum, int16x8_t *sub,
                                  const int16x8_t a, const int16x8_t b)
{
    *sum = vabsq_s16(vaddq_s16(a, b));
    *sub = vabdq_s16(a, b);
}

static const uint16_t HAD_IDX16[16] =
    { 0, 2, 4, 6, 1, 3, 5, 7, 8, 10, 12, 14, 9, 11, 13, 15 };
static const uint16_t HAD_IDX_HI[16] =
    { 8, 9, 10, 11, 12, 13, 14, 15, 8, 9, 10, 11, 12, 13, 14, 15 };

} // namespace

extern "C" int %s(const uint8_t* pix1, intptr_t stride_pix1,
                  const uint8_t* pix2, intptr_t stride_pix2)
{
    const svbool_t p16 = svptrue_b16();
    const svbool_t pg8 = svwhilelt_b16(0, 8);
    const svbool_t pg_hi = svnot_b_z(svptrue_b16(), pg8);
    const svuint16_t had_idx = svld1_u16(p16, HAD_IDX16);
    const svuint16_t hi_idx = svld1_u16(p16, HAD_IDX_HI);

    // 4 explicitly unrolled row-pairs: two rows per 16-lane register. Fixed
    // locals (not an indexed array) let GCC keep the extracted rows in NEON
    // registers through the free SVE<->NEON bridge instead of spilling to
    // the stack (a loop with `diff[i]` costs 12 extra vector stores/loads).
    //
    // Loading two rows into the SAME SVE register with two predicated loads
    // is miscompiled by GCC (it merges them into one load with the wrong
    // predicate), so each row loads into its own register and is merged with
    // SEL/MOV (one instruction, low half = row i, high half = row i+1).
    //
    // Predicated ld1ub addresses active lanes BY BYTE OFFSET: lane k reads
    // byte (ptr + k), so a pg_hi load must point 8 bytes BEFORE the target
    // row to land pixels 0..7 in lanes 8..15.
    #define ROW_H(pname, a_expr, b_expr)                                  \
        svint16_t pname = svreinterpret_s16_u16(                          \
            svsub_u16_x(p16, (a_expr), (b_expr)));                        \
        pname = svcadd_s16(pname, pname, 90);                             \
        pname = svtbl_s16(pname, had_idx);                                \
        pname = svcadd_s16(pname, pname, 90);                             \
        pname = svtbl_s16(pname, had_idx);                                \
        pname = svcadd_s16(pname, pname, 90);                             \
        (void)0

    #define PACK(px, s, i)                                                \
        svsel_u16(pg_hi,                                                   \
                  svld1ub_u16(pg_hi, (px) + ((i) + 1) * (s) - 8),          \
                  svld1ub_u16(pg8, (px) + (i) * (s)))

    int16x8_t diff0, diff1, diff2, diff3, diff4, diff5, diff6, diff7;

    ROW_H(p0, PACK(pix1, stride_pix1, 0), PACK(pix2, stride_pix2, 0));
    diff0 = svget_neonq_s16(p0);
    diff1 = svget_neonq_s16(svtbl_s16(p0, hi_idx));

    ROW_H(p1, PACK(pix1, stride_pix1, 2), PACK(pix2, stride_pix2, 2));
    diff2 = svget_neonq_s16(p1);
    diff3 = svget_neonq_s16(svtbl_s16(p1, hi_idx));

    ROW_H(p2, PACK(pix1, stride_pix1, 4), PACK(pix2, stride_pix2, 4));
    diff4 = svget_neonq_s16(p2);
    diff5 = svget_neonq_s16(svtbl_s16(p2, hi_idx));

    ROW_H(p3, PACK(pix1, stride_pix1, 6), PACK(pix2, stride_pix2, 6));
    diff6 = svget_neonq_s16(p3);
    diff7 = svget_neonq_s16(svtbl_s16(p3, hi_idx));

    // Upstream row-combine and reduction (unchanged).
    int16x8_t a0, a1, a2, a3, a4, a5, a6, a7;
    int16x8_t b0, b1, b2, b3, b4, b5, b6, b7;
    sumsubq_s16(&b0, &b1, diff0, diff1);
    sumsubq_s16(&b2, &b3, diff2, diff3);
    sumsubq_s16(&b4, &b5, diff4, diff5);
    sumsubq_s16(&b6, &b7, diff6, diff7);

    abssumsubq_s16(&a0, &a2, b0, b2);
    abssumsubq_s16(&a1, &a3, b1, b3);
    abssumsubq_s16(&a4, &a6, b4, b6);
    abssumsubq_s16(&a5, &a7, b5, b7);

    uint16x8_t max0 = vmaxq_u16(vreinterpretq_u16_s16(a0),
                                vreinterpretq_u16_s16(a4));
    uint16x8_t max1 = vmaxq_u16(vreinterpretq_u16_s16(a1),
                                vreinterpretq_u16_s16(a5));
    uint16x8_t max2 = vmaxq_u16(vreinterpretq_u16_s16(a2),
                                vreinterpretq_u16_s16(a6));
    uint16x8_t max3 = vmaxq_u16(vreinterpretq_u16_s16(a3),
                                vreinterpretq_u16_s16(a7));

    uint16x8_t sum0 = vaddq_u16(max0, max1);
    uint16x8_t sum1 = vaddq_u16(max2, max3);
    uint64x2_t sum = vdupq_n_u64(0);
    sum = udotq_u16(sum, sum0, vdupq_n_u16(1));
    sum = udotq_u16(sum, sum1, vdupq_n_u16(1));

    return (vaddvq_u64(sum) + 1) >> 1;
}
""" % func_name


def emit_single(func_name):
    """pack=1: open-source-equivalent 8-lane port (correctness anchor)."""
    raise NotImplementedError("single-row variant: use the open-source "
                              "sa8d8_sve2 as the baseline")


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("out", default="generated/sa8d/sve2_8x8.cpp")
    ap.add_argument("--pack", type=int, default=2)
    args = ap.parse_args()
    with open(args.out, "w") as f:
        f.write(emit(pack=args.pack))
    print("wrote %s" % args.out)


if __name__ == "__main__":
    main()
