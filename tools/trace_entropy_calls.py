#!/usr/bin/env python3
"""Generate a diagnostic x265 build that records every call to the four
entropy hot kernels (costC1C2Flag / costCoeffRemain / costCoeffNxN /
scanPosLast) into a binary trace, plus the wrappers' object.

Purpose (expert-advice round-0021, P0): replace synthetic-distribution
microbenchmarks with a real-call replay corpus captured on the target
920B during an actual encode, so kernel rankings use the true call mix.
The wrapper calls the original primitive (bitstream unchanged) and only
appends an input snapshot when DYNOPT_TRACE_PATH is set.

Usage:
  python3 tools/trace_entropy_calls.py [outdir] [--cxx ...]

Outputs (outdir default build/trace-entropy):
  trace_rec.cpp / trace_rec.o      wrapper implementation + object
  x265-dynopt-trace.patch          primitives.cpp diff (call wrapper once)

Cloud integration:
  scp trace_rec.o x265-dynopt-trace.patch to the cloud repo, apply the
  patch, add trace_rec.o to the libx265.so.216 ninja link line, rebuild,
  then run the encoder with DYNOPT_TRACE_PATH=/path/trace.bin. Restore
  the clean build afterwards.
"""

import argparse
import difflib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


WRAPPER_SRC = r"""\
// Generated by tools/trace_entropy_calls.py -- do not edit.
// Diagnostic wrappers: forward to the original primitive (bitstream
// unchanged) and, when DYNOPT_TRACE_PATH is set, append a compact input
// snapshot for real-call replay (expert-advice round-0021 P0).
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cstdint>
#include "common/primitives.h"

using namespace X265_NS;

static FILE* g_tr = 0;

static void trace_init()
{
    const char* p = getenv("DYNOPT_TRACE_PATH");
    if (p)
        g_tr = fopen(p, "wb");
}

static inline void tw(const void* d, size_t n)
{
    if (g_tr)
        fwrite(d, 1, n, g_tr);
}

// ---- costC1C2Flag: id=1, n(u8), abs[8](u16), ctx[64](u8), off(i64) ----
static costC1C2Flag_t g_o_c1 = 0;
static uint32_t w_c1(uint16_t* absCoeff, intptr_t numC1Flag,
                     uint8_t* baseCtxMod, intptr_t ctxOffset)
{
    uint8_t a0[16], c0[64];
    memcpy(a0, absCoeff, 16);
    memcpy(c0, baseCtxMod, 64);
    const uint32_t r = g_o_c1(absCoeff, numC1Flag, baseCtxMod, ctxOffset);
    if (g_tr)
    {
        const uint8_t id = 1, n = (uint8_t)numC1Flag;
        tw(&id, 1);
        tw(&n, 1);
        tw(a0, 16);
        tw(c0, 64);
        tw(&ctxOffset, sizeof(ctxOffset));
    }
    return r;
}

// ---- costCoeffRemain: id=2, numNonZero(u16), idx(u16), abs[16](u16) ----
static costCoeffRemain_t g_o_re = 0;
static uint32_t w_re(uint16_t* absCoeff, int numNonZero, int idx)
{
    uint16_t a0[16];
    memcpy(a0, absCoeff + (idx >= 0 ? idx : 0), 32);
    const uint32_t r = g_o_re(absCoeff, numNonZero, idx);
    if (g_tr)
    {
        const uint8_t id = 2;
        uint16_t nn = (uint16_t)numNonZero, ix = (uint16_t)idx;
        tw(&id, 1);
        tw(&nn, 2);
        tw(&ix, 2);
        tw(a0, 32);
    }
    return r;
}

// ---- costCoeffNxN: id=3 ----
// payload: trSize(i64), mask(u32), offset(i32), soff(i32), sub(i32),
//          coeff[16](s16: rows i*trSize+0..3), tab[16](u8),
//          ctx[64](u8), scan[16](u16)
static costCoeffNxN_t g_o_cc = 0;
static uint32_t w_cc(const uint16_t* scan, const coeff_t* coeff,
                     intptr_t trSize, uint16_t* absCoeff,
                     const uint8_t* tabSigCtx, uint32_t scanFlagMask,
                     uint8_t* baseCtx, int offset, int scanPosSigOff,
                     int subPosBase)
{
    int16_t c0[16];
    for (int i = 0; i < 4; i++)
        memcpy(c0 + 4 * i, coeff + i * trSize, 8);
    uint8_t t0[16], b0[64];
    uint16_t s0[16];
    memcpy(t0, tabSigCtx, 16);
    memcpy(b0, baseCtx, 64);
    memcpy(s0, scan, 32);
    const uint32_t r = g_o_cc(scan, coeff, trSize, absCoeff, tabSigCtx,
                              scanFlagMask, baseCtx, offset,
                              scanPosSigOff, subPosBase);
    if (g_tr)
    {
        const uint8_t id = 3;
        int32_t off = offset, so = scanPosSigOff, sub = subPosBase;
        tw(&id, 1);
        tw(&trSize, sizeof(trSize));
        tw(&scanFlagMask, 4);
        tw(&off, 4);
        tw(&so, 4);
        tw(&sub, 4);
        tw(c0, 32);
        tw(t0, 16);
        tw(b0, 64);
        tw(s0, 32);
    }
    return r;
}

// ---- scanPosLast: id=4 ----
// payload: trSize(u16), numSig(u16), ncg(u16), vals[ncg*16](s16),
//          scan[trSize*trSize](u16), cg4x4[16](u16)
static scanPosLast_t g_o_sc = 0;
static int w_sc(const uint16_t* scan, const coeff_t* coeff,
                uint16_t* coeffSign, uint16_t* coeffFlag,
                uint8_t* coeffNum, int numSig,
                const uint16_t* scanCG4x4, const int trSize)
{
    uint16_t s0[1024], g0[16];
    const int scanlen = trSize * trSize;
    memcpy(s0, scan, (size_t)scanlen * 2);
    memcpy(g0, scanCG4x4, 32);
    // The kernel visits every CG that contains at least one nonzero
    // coefficient; ceil(numSig/16) is only a lower bound (round-0021
    // replay bug: sparse CGs made the C reference scan past the recorded
    // values). Collect the actually-visited CGs in scan order.
    int cglist[64];
    int ncgs = 0;
    for (int i = 0; i < scanlen && ncgs < 64; i++)
    {
        if (coeff[s0[i]])
        {
            const int cg = i >> 4;
            if (ncgs == 0 || cglist[ncgs - 1] != cg)
                cglist[ncgs++] = cg;
        }
    }
    const int ncg = ncgs;
    int16_t vals[1024];
    int cnt = 0;
    for (int i = 0; i < ncg; i++)
    {
        const int off = s0[16 * cglist[i]];
        for (int k = 0; k < 4; k++)
            for (int j = 0; j < 4; j++)
                vals[cnt++] = coeff[off + k * trSize + j];
    }
    const int r = g_o_sc(scan, coeff, coeffSign, coeffFlag, coeffNum,
                         numSig, scanCG4x4, trSize);
    if (g_tr)
    {
        const uint8_t id = 4;
        uint16_t t = (uint16_t)trSize, ns = (uint16_t)numSig,
                 nc = (uint16_t)ncg;
        tw(&id, 1);
        tw(&t, 2);
        tw(&ns, 2);
        tw(&nc, 2);
        tw(vals, (size_t)cnt * 2);
        tw(s0, (size_t)scanlen * 2);
        tw(g0, 32);
    }
    return r;
}

extern "C" void dynopt_trace_wrap_all(void)
{
    trace_init();
    g_o_c1 = primitives.costC1C2Flag;
    primitives.costC1C2Flag = w_c1;
    g_o_re = primitives.costCoeffRemain;
    primitives.costCoeffRemain = w_re;
    g_o_cc = primitives.costCoeffNxN;
    primitives.costCoeffNxN = w_cc;
    g_o_sc = primitives.scanPosLast;
    primitives.scanPosLast = w_sc;
}
"""


def write_patch(outdir):
    prim = os.path.join(ROOT, "third_party/x265/source/common",
                        "primitives.cpp")
    src = open(prim).read().splitlines()
    mod = list(src)
    for i, line in enumerate(mod):
        if line.strip() == "namespace X265_NS {" and \
                mod[i + 1].strip().startswith("// x265 private namespace"):
            mod.insert(i + 2,
                       'extern "C" void dynopt_trace_wrap_all();')
            break
    for i, line in enumerate(mod):
        if line.strip() == "setupAliasPrimitives(primitives);":
            mod.insert(i + 1, "        dynopt_trace_wrap_all();")
            break
    diff = difflib.unified_diff(
        src, mod,
        fromfile="a/source/common/primitives.cpp",
        tofile="b/source/common/primitives.cpp", lineterm="")
    path = os.path.join(outdir, "x265-dynopt-trace.patch")
    with open(path, "w") as f:
        f.write("\n".join(diff) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir", nargs="?", default="build/trace-entropy")
    ap.add_argument("--cxx", default="aarch64-linux-gnu-g++")
    args = ap.parse_args()
    outdir = os.path.join(ROOT, args.outdir)
    os.makedirs(outdir, exist_ok=True)
    src_path = os.path.join(outdir, "trace_rec.cpp")
    obj_path = os.path.join(outdir, "trace_rec.o")
    with open(src_path, "w") as f:
        f.write(WRAPPER_SRC)
    r = subprocess.run(
        [args.cxx, "-O2", "-fPIC", "-std=c++11", "-DX265_NS=x265",
         "-DX265_DEPTH=8", "-DHIGH_BIT_DEPTH=0",
         "-I", os.path.join(ROOT, "third_party/x265/source"),
         "-I", os.path.join(ROOT, "third_party/x265/source/common"),
         "-I", os.path.join(ROOT, "build/x265-8-cross-make"),
         "-c", src_path, "-o", obj_path],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode != 0:
        sys.exit("trace_rec compile failed:\n" + r.stdout[-3000:])
    patch = write_patch(outdir)
    print("wrote %s" % src_path)
    print("wrote %s" % patch)
    print("wrote %s" % obj_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
