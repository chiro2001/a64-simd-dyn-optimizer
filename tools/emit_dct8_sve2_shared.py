#!/usr/bin/env python3
"""Parameterized SVE2 (VL=256) emitter for DCT8, manifest-driven (docs/16).

The emitted kernel is an op-for-op port of x265's upstream
`partialButterfly8_sve` (open source, third_party/x265), which defines the
upstream-exact contract for DCT8:
  - E is widened to s32 (vaddl, no wrap);
  - O stays s16 (vsubq_s16, wraps when |coef| is large -> this is the
    upstream's known ~0.868% divergence from the C reference);
  - odd k uses O via NEON sdot (s16 x s16 -> s64);
  - even k uses s32 EE/EO via vmul/vpadd/vrshrn.
Both passes use the same template (shift 2 then 9), matching dct8_sve.

The old quarter-pack s16-sdot emitter was dropped: it wrapped E as well,
producing a 0.11% divergence that satisfied neither upstream-exact nor
C-exact. Future SVE2 optimization of DCT8 can start from this verified
baseline and re-apply the DCT16 learnings (zip packs, even-factor, etc.).
"""


def emit(func_name="dynopt_dct8_sve2_shared", k_tile=1):
    return """\
// Generated by tools/emit_dct8_sve2_shared.py -- do not edit by hand.
// Op-for-op port of x265 partialButterfly8_sve (upstream-exact DCT8).
#include <arm_neon.h>
#include <arm_neon_sve_bridge.h>
#include <cstring>

namespace {

static inline int64x2_t sdotq_s16(int64x2_t acc, int16x8_t x, int16x8_t y)
{
    return svget_neonq_s64(svdot_s64(
        svset_neonq_s64(svundef_s64(), acc),
        svset_neonq_s16(svundef_s16(), x),
        svset_neonq_s16(svundef_s16(), y)));
}

static const int32_t T8_EVEN[4][4] = {
    { 64,  64, 64,  64 },
    { 83,  36, 83,  36 },
    { 64, -64, 64, -64 },
    { 36, -83, 36, -83 },
};

static const int16_t T8_ODD[4][8] = {
    { 89,  75,  50,  18, 89,  75,  50,  18 },
    { 75, -18, -89, -50, 75, -18, -89, -50 },
    { 50, -89,  18,  75, 50, -89,  18,  75 },
    { 18, -50,  75, -89, 18, -50,  75, -89 },
};

template <int shift>
static void pass8(const int16_t* src, int16_t* dst)
{
    const int line = 8;

    int16x8_t O[line / 2];
    int32x4_t EE[line / 2];
    int32x4_t EO[line / 2];

    for (int i = 0; i < line; i += 2)
    {
        int16x8_t s_lo = vcombine_s16(vld1_s16(src + i * line),
                                      vld1_s16(src + (i + 1) * line));
        int16x8_t s_hi = vcombine_s16(
            vrev64_s16(vld1_s16(src + i * line + 4)),
            vrev64_s16(vld1_s16(src + (i + 1) * line + 4)));

        int32x4_t E0 = vaddl_s16(vget_low_s16(s_lo), vget_low_s16(s_hi));
        int32x4_t E1 = vaddl_s16(vget_high_s16(s_lo), vget_high_s16(s_hi));

        O[i / 2] = vsubq_s16(s_lo, s_hi);

        int32x4_t t0 = vreinterpretq_s32_s64(
            vzip1q_s64(vreinterpretq_s64_s32(E0),
                       vreinterpretq_s64_s32(E1)));
        int32x4_t t1 = vrev64q_s32(vreinterpretq_s32_s64(
            vzip2q_s64(vreinterpretq_s64_s32(E0),
                       vreinterpretq_s64_s32(E1))));

        EE[i / 2] = vaddq_s32(t0, t1);
        EO[i / 2] = vsubq_s32(t0, t1);
    }

    int16_t* d = dst;

    int32x4_t c0 = vld1q_s32(T8_EVEN[0]);
    int32x4_t c2 = vld1q_s32(T8_EVEN[1]);
    int32x4_t c4 = vld1q_s32(T8_EVEN[2]);
    int32x4_t c6 = vld1q_s32(T8_EVEN[3]);
    int16x8_t c1 = vld1q_s16(T8_ODD[0]);
    int16x8_t c3 = vld1q_s16(T8_ODD[1]);
    int16x8_t c5 = vld1q_s16(T8_ODD[2]);
    int16x8_t c7 = vld1q_s16(T8_ODD[3]);

    for (int j = 0; j < line; j += 4)
    {
        int64x2_t t01 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 0], c1);
        int64x2_t t23 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 1], c1);
        int32x4_t t0123 = vcombine_s32(vmovn_s64(t01), vmovn_s64(t23));
        int16x4_t res1 = vrshrn_n_s32(t0123, shift);
        vst1_s16(d + 1 * line, res1);

        t01 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 0], c3);
        t23 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 1], c3);
        t0123 = vcombine_s32(vmovn_s64(t01), vmovn_s64(t23));
        int16x4_t res3 = vrshrn_n_s32(t0123, shift);
        vst1_s16(d + 3 * line, res3);

        t01 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 0], c5);
        t23 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 1], c5);
        t0123 = vcombine_s32(vmovn_s64(t01), vmovn_s64(t23));
        int16x4_t res5 = vrshrn_n_s32(t0123, shift);
        vst1_s16(d + 5 * line, res5);

        t01 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 0], c7);
        t23 = sdotq_s16(vdupq_n_s64(0), O[j / 2 + 1], c7);
        t0123 = vcombine_s32(vmovn_s64(t01), vmovn_s64(t23));
        int16x4_t res7 = vrshrn_n_s32(t0123, shift);
        vst1_s16(d + 7 * line, res7);

        int32x4_t t0 = vpaddq_s32(EE[j / 2 + 0], EE[j / 2 + 1]);
        int32x4_t t1 = vmulq_s32(c0, t0);
        int16x4_t res0 = vrshrn_n_s32(t1, shift);
        vst1_s16(d + 0 * line, res0);

        int32x4_t t2 = vmulq_s32(c2, EO[j / 2 + 0]);
        int32x4_t t3 = vmulq_s32(c2, EO[j / 2 + 1]);
        int16x4_t res2 = vrshrn_n_s32(vpaddq_s32(t2, t3), shift);
        vst1_s16(d + 2 * line, res2);

        int32x4_t t4 = vmulq_s32(c4, EE[j / 2 + 0]);
        int32x4_t t5 = vmulq_s32(c4, EE[j / 2 + 1]);
        int16x4_t res4 = vrshrn_n_s32(vpaddq_s32(t4, t5), shift);
        vst1_s16(d + 4 * line, res4);

        int32x4_t t6 = vmulq_s32(c6, EO[j / 2 + 0]);
        int32x4_t t7 = vmulq_s32(c6, EO[j / 2 + 1]);
        int16x4_t res6 = vrshrn_n_s32(vpaddq_s32(t6, t7), shift);
        vst1_s16(d + 6 * line, res6);

        d += 4;
    }
}

} // namespace

extern "C" void %s(const int16_t* src, int16_t* dst, intptr_t srcStride)
{
    int16_t block[8 * 8];
    int16_t coef[8 * 8];
    for (int i = 0; i < 8; i++)
        memcpy(&block[i * 8], &src[i * srcStride], 8 * sizeof(int16_t));
    pass8<2>(block, coef);
    pass8<9>(coef, dst);
}
""" % func_name


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("out", default="kernels/dct8/candidates/sve2_shared.cpp",
                    nargs="?")
    ap.add_argument("--k-tile", type=int, default=1)
    args = ap.parse_args()
    with open(args.out, "w") as f:
        f.write(emit(k_tile=args.k_tile))
    print("wrote %s" % args.out)


if __name__ == "__main__":
    main()
