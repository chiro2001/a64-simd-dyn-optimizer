#!/usr/bin/env python3
"""Generate the upstream-exact differential harness from a kernel manifest.

The manifest (docs/16) declares the reference symbol/declaration, corpus
(strides, value range, cases) and VL contract; this generator turns it into
a self-contained C++ verify source so the evaluation funnel is manifest-
driven and no per-kernel harness needs to be hand-maintained.

Usage:
  python3 tools/gen_verify.py --manifest kernels/dct16/manifest.yaml \
      --out build/dct16_generated_verify.cpp
"""

import argparse
import sys
import os
import string

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from kernel_manifest import load_manifest  # noqa: E402


def generate(manifest):
    ref = manifest["reference"]
    cand = manifest["candidate"]
    corpus = manifest.get("corpus", {})
    strides = corpus.get("strides", [16])
    lo, hi = corpus.get("value_range", [-255, 255])
    vl = manifest.get("vl_bytes", 32)
    cases = corpus.get("cases", 20000)
    n = manifest.get("shape", {}).get("n", 16)
    n_out = n * n
    strides_c = ", ".join(str(s) for s in strides)
    nstrides = len(strides)
    t = string.Template("""\
// Generated by tools/gen_verify.py from ${path} -- do not edit by hand.
// Contract: ${contract}, fixed VL=${vl} bytes.
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <random>
#include <sys/prctl.h>

${decl}

extern "C" void ${cand_sym}(const int16_t*, int16_t*, intptr_t);

int main(int argc, char** argv)
{
#ifndef PR_SVE_SET_VL
#define PR_SVE_SET_VL 50
#endif
    const int vl = prctl(PR_SVE_SET_VL, ${vl}, 0, 0, 0, 0);
    if (vl < 0)
    {
        perror("prctl(PR_SVE_SET_VL)");
        return 77;
    }
    if (vl != ${vl})
    {
        fprintf(stderr, "prctl returned VL=%d bytes, contract requires ${vl}\\n",
                vl);
        return 78;
    }

    const int cases = argc > 1 ? atoi(argv[1]) : ${cases};
    std::mt19937 rng(0xD16C2026u);
    const int strides[${nstrides}] = { ${strides_c} };

    long mism = 0, total = 0;
    int first_k = -1;
    int16_t first_want = 0, first_got = 0;
    for (int i = 0; i < cases; i++)
    {
        const int stride = strides[rng() % ${nstrides}];
        int16_t buf[${n} * 32 + ${n}];
        for (int j = 0; j < (int)(sizeof(buf) / sizeof(buf[0])); j++)
            buf[j] = (int16_t)((int)(rng() % (${hi} - ${lo} + 1)) + ${lo});

        int16_t want[${n_out}], got[${n_out}];
        ${ref_call}(buf, want, stride);
        memset(got, 0, sizeof(got));
        ${cand_sym}(buf, got, stride);
        total += ${n_out};
        for (int k = 0; k < ${n_out}; k++)
            if (want[k] != got[k])
            {
                mism++;
                if (first_k < 0)
                {
                    first_k = k;
                    first_want = want[k];
                    first_got = got[k];
                }
            }
    }
    printf("cases=%d lanes=%ld mismatches=%ld rate=%f%%\\n",
           cases, total, mism, 100.0 * mism / total);
    if (first_k >= 0)
        printf(" first-diff idx=%d want=%d got=%d\\n",
               first_k, first_want, first_got);
    return mism != 0;
}
"""
    )
    return t.substitute(
        path=manifest["_path"], contract=manifest.get("contract", "?"),
        vl=vl, decl=ref["decl"], cand_sym=cand["symbol"],
        cases=cases, nstrides=nstrides, strides_c=strides_c,
        n=n, n_out=n_out, hi=hi, lo=lo, ref_call=ref["call"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default="kernels/dct16/manifest.yaml")
    ap.add_argument("--out", default="build/dct16_generated_verify.cpp")
    args = ap.parse_args()
    manifest = load_manifest(
        os.path.basename(os.path.dirname(args.manifest)))
    src = generate(manifest)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(src)
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
