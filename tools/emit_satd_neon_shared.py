#!/usr/bin/env python3
"""Pure-NEON SATD 8x8 emitter for 920B (round-0024).

The x265 NEON satd is a compiler-generated C++ template
(pixel_satd_8x8_neon / satd8_neon<8,8>), not handwritten asm, so a
searchable NEON lowering has a realistic chance of matching or beating
it.  This emitter ports the 4x4-quad Hadamard structure and searches:

  reduce  vaddlv  upstream: vaddq_u16(out0,out1) + vaddlvq_u16
          vpaddl  u16 lane sums widened once + vaddvq_u32
          vaddv   scalar u16 horizontal sums per half

Contract: bit-exact with x265's satd8_sve2<8,8> (integer SATD), gated by
the existing satd-8 upstream-exact verifier.
"""


def emit_8x8(func_name="dynopt_satd_8x8_sve2", reduce="vaddlv"):
    if reduce not in ("vaddlv", "vpaddl", "vaddv"):
        raise ValueError("unknown reduce %r" % reduce)

    if reduce == "vaddlv":
        red = ("    uint16x8_t sum = vaddq_u16(out[0], out[1]);\n"
               "    return (int)vaddlvq_u16(sum);")
    elif reduce == "vpaddl":
        red = ("    uint32x4_t s = vpaddlq_u16(out[0]);\n"
               "    s = vpadalq_u16(s, out[1]);\n"
               "    return (int)vaddvq_u32(s);")
    else:
        red = ("    return (int)(vaddvq_u16(out[0]) + "
               "vaddvq_u16(out[1]));")

    return """\
// Generated by tools/emit_satd_neon_shared.py -- do not edit by hand.
// SATD 8x8 pure NEON, reduce=%(reduce)s.
#include <arm_neon.h>
#include <stdint.h>

static inline void sumsubq_s16(int16x8_t *sum, int16x8_t *sub,
                               const int16x8_t a, const int16x8_t b)
{
    *sum = vaddq_s16(a, b);
    *sub = vsubq_s16(a, b);
}

static inline void abssumsubq_s16(int16x8_t *sum, int16x8_t *sub,
                                  const int16x8_t a, const int16x8_t b)
{
    *sum = vabsq_s16(vaddq_s16(a, b));
    *sub = vabdq_s16(a, b);
}

static inline void transpose_s16_s16x2(int16x8_t *t1, int16x8_t *t2,
                                       const int16x8_t s1,
                                       const int16x8_t s2)
{
    *t1 = vtrn1q_s16(s1, s2);
    *t2 = vtrn2q_s16(s1, s2);
}

static inline void transpose_s16_s32x2(int16x8_t *t1, int16x8_t *t2,
                                       const int16x8_t s1,
                                       const int16x8_t s2)
{
    *t1 = vreinterpretq_s16_s32(
        vtrn1q_s32(vreinterpretq_s32_s16(s1), vreinterpretq_s32_s16(s2)));
    *t2 = vreinterpretq_s16_s32(
        vtrn2q_s32(vreinterpretq_s32_s16(s1), vreinterpretq_s32_s16(s2)));
}

static inline void hadamard_4_v(const int16x8_t in[4], int16x8_t out[4])
{
    int16x8_t s0, s1, d0, d1;
    sumsubq_s16(&s0, &d0, in[0], in[1]);
    sumsubq_s16(&s1, &d1, in[2], in[3]);
    sumsubq_s16(&out[0], &out[2], s0, s1);
    sumsubq_s16(&out[1], &out[3], d0, d1);
}

static inline void hadamard_abs_4_h(const int16x8_t in[4],
                                    int16x8_t out[4])
{
    int16x8_t s0, s1, d0, d1, t0, t1, t2, t3;
    transpose_s16_s16x2(&t0, &t1, in[0], in[1]);
    transpose_s16_s16x2(&t2, &t3, in[2], in[3]);
    abssumsubq_s16(&s0, &d0, t0, t1);
    abssumsubq_s16(&s1, &d1, t2, t3);
    transpose_s16_s32x2(&out[0], &out[1], s0, s1);
    transpose_s16_s32x2(&out[2], &out[3], d0, d1);
}

static inline void hadamard_4x4_quad(int16x8_t diff[8],
                                     uint16x8_t out[2])
{
    int16x8_t temp[8];
    hadamard_4_v(diff, temp);
    hadamard_4_v(diff + 4, temp + 4);
    hadamard_abs_4_h(temp, diff);
    hadamard_abs_4_h(temp + 4, diff + 4);
    uint16x8_t sum0 = vmaxq_u16(vreinterpretq_u16_s16(diff[0]),
                                vreinterpretq_u16_s16(diff[1]));
    uint16x8_t sum1 = vmaxq_u16(vreinterpretq_u16_s16(diff[2]),
                                vreinterpretq_u16_s16(diff[3]));
    uint16x8_t sum2 = vmaxq_u16(vreinterpretq_u16_s16(diff[4]),
                                vreinterpretq_u16_s16(diff[5]));
    uint16x8_t sum3 = vmaxq_u16(vreinterpretq_u16_s16(diff[6]),
                                vreinterpretq_u16_s16(diff[7]));
    out[0] = vaddq_u16(sum0, sum1);
    out[1] = vaddq_u16(sum2, sum3);
}

extern "C" int %(func)s(const uint8_t* pix1, intptr_t sp1,
                        const uint8_t* pix2, intptr_t sp2)
{
    int16x8_t diff[8];
    for (int y = 0; y < 8; y++)
        diff[y] = vreinterpretq_s16_u16(vsubl_u8(
            vld1_u8(pix1 + y * sp1), vld1_u8(pix2 + y * sp2)));
    uint16x8_t out[2];
    hadamard_4x4_quad(diff, out);
%(red)s
}
""" % {"reduce": reduce, "func": func_name, "red": red}


def emit_combo(combo):
    return emit_8x8(reduce=combo.get("reduce", "vaddlv"))


def _helpers():
    """Reusable NEON helper preamble (transposes + hadamard)."""
    return emit_8x8().split('extern "C" int ')[0]


def _16x16_body(func_name="dynopt_satd_16x16_sve2"):
    return """\
static int %(func)s_impl(const uint8_t* pix1, intptr_t sp1,
                         const uint8_t* pix2, intptr_t sp2)
{
    uint16x8_t sum[2], out[2];
    int16x8_t diff[8];
    for (int g = 0; g < 4; g++)
    {
        for (int y = 0; y < 4; y++)
        {
            const uint8_t* p1 = pix1 + (g * 4 + y) * sp1;
            const uint8_t* p2 = pix2 + (g * 4 + y) * sp2;
            const uint8x16_t s = vld1q_u8(p1);
            const uint8x16_t r = vld1q_u8(p2);
            diff[y] = vreinterpretq_s16_u16(vsubl_u8(
                vget_low_u8(s), vget_low_u8(r)));
            diff[y + 4] = vreinterpretq_s16_u16(vsubl_u8(
                vget_high_u8(s), vget_high_u8(r)));
        }
        hadamard_4x4_quad(diff, out);
        if (g == 0)
        {
            sum[0] = out[0];
            sum[1] = out[1];
        }
        else
        {
            sum[0] = vaddq_u16(sum[0], out[0]);
            sum[1] = vaddq_u16(sum[1], out[1]);
        }
    }
    uint32x4_t s0 = vpaddlq_u16(sum[0]);
    uint32x4_t s1 = vpaddlq_u16(sum[1]);
    return (int)vaddvq_u32(vaddq_u32(s0, s1));
}

extern "C" int %(func)s(const uint8_t* pix1, intptr_t sp1,
                        const uint8_t* pix2, intptr_t sp2)
{
    return %(func)s_impl(pix1, sp1, pix2, sp2);
}
""" % {"func": func_name}


def emit_16x16(func_name="dynopt_satd_16x16_sve2"):
    """SATD 16x16 NEON: 4 row-groups x (left/right 4x4 quad), u16 lane
    accumulation + vpaddl/vaddvq (upstream pixel_satd_16x16_neon)."""
    return _helpers() + _16x16_body(func_name)


def emit_all(func_8="dynopt_satd_8x8_sve2", func_16="dynopt_satd_16x16_sve2",
             reduce="vpaddl"):
    """8x8 + 16x16 primitives + 32x32/64x64 wrappers for injection."""
    src = emit_8x8(func_name=func_8, reduce=reduce)
    src += _16x16_body(func_name=func_16)
    for n in (32, 64):
        loops = []
        for y in range(0, n, 16):
            for x in range(0, n, 16):
                loops.append(
                    "        cost += %s_impl(pix1 + %d * sp1 + %d, sp1,\n"
                    "                       pix2 + %d * sp2 + %d, sp2);"
                    % (func_16, y, x, y, x))
        src += """\

extern "C" int dynopt_satd_%(n)dx%(n)d_sve2(
    const uint8_t* pix1, intptr_t sp1,
    const uint8_t* pix2, intptr_t sp2)
{
    int cost = 0;
%(loops)s
    return cost;
}
""" % {"n": n, "loops": "\n".join(loops)}
    return src
