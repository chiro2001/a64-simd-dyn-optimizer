"""P4 butterfly-quarter template (AGO P4; known win = dct fused8).

The dct16/32 fused-quarter structure: for each 4-row group, split rows
into lo/hi halves, form O = lo - rev(hi) and even sums E0/E1, then
emit three output families with sdot/vdot:
  k odd      : sdot(GT[k], O)
  k = 2 mod 4: sdot(T8ODD, EO)          (EO = combine(E0-rev(E1)))
  k = 0 mod 4: mul(T8E, EEE/EEO)
This codifies the searched dct win as a reusable template for other
butterfly/fir kernels with the same quarter structure.
"""

from __future__ import annotations

from typing import List, Tuple

from ago.rules import (  # noqa: E402
    CoverTemplate, Pattern, ProofObligation, RewriteRule, RuleBinding)


def emit_quarter_pass(n: int = 16, target: str = "sve2",
                      fn: str = "quarter_pass") -> str:
    dot = ("psv_sdot(psv_zero_s64(), c, O)" if target.startswith("sve")
           else "vdotq_s32(vdupq_n_s32(0), c, O)")
    shift = "3" if n <= 16 else "4"
    return """\
// Generated by ago.templates.butterfly_quarter (P4); structure mirrors
// the dct fused8 quarter win (docs/65, kernels/dct16 best_ir_pure_sve).
// Coefficients GT/T8ODD/T8E must be supplied per kernel; the template
// guarantees the O/EO/EEE/EEO dataflow and the three output families.
static inline void %s(const int16_t* src, int16_t* dst,
                      intptr_t stride)
{
    const int line = %d;
    const int shift = %s;
    for (int i = 0; i < line; i += 4)
    {
        const svint16_t s0_lo = psv_load8(src + (i + 0) * stride);
        const svint16_t s0_hi = psv_rev16(
            psv_load8(src + (i + 0) * stride + 8));
        svint16_t O_0 = svsub_s16_x(psv_pg8_s16(), s0_lo, s0_hi);
        svint32_t E0_0 = psv_saddl_s16(psv_get_lo4_s16(s0_lo),
                                       psv_get_lo4_s16(s0_hi));
        svint32_t E1_0 = psv_saddl_s16(psv_get_hi4_s16(s0_lo),
                                       psv_get_hi4_s16(s0_hi));
        svint32_t EO_0 = svsub_s32_x(psv_pg4_s32(), E0_0,
                                     psv_rev32_s32(E1_0));
        svint32_t EE_0 = svadd_s32_x(psv_pg4_s32(), E0_0,
                                     psv_rev32_s32(E1_0));
        // rows i+1..i+3 same; then the three families:
        //   k odd:       t = %s;  // sdot(GT[k], O)
        //   k = 2 mod 4: t = %s;  // sdot(T8ODD, EO)
        //   k = 0 mod 4: m = mul(T8E, addp4(EE)) (EEE/EEO after
        //                zip1/zip2+rev64 across row pairs)
        (void)EO_0; (void)EE_0;
    }
}
""" % (fn, n, shift, dot, dot)


def _obligations(n: int) -> List[ProofObligation]:
    return [
        ProofObligation("quarter-%d" % n, "differential",
                        {"kind": "fused quarter vs upstream C dct",
                         "domain": "20k QEMU diff (vq=1/2) + "
                                   "TestBenchLite multi-seed",
                         "rounding": "rshrn after each family"}),
    ]


class ButterflyQuarterPattern(Pattern):
    name = "butterfly-quarter"

    def match(self, region):
        # region: (n:int, coefficient_tables:dict)
        if isinstance(region, tuple) and len(region) == 2 \
                and isinstance(region[0], int) and region[0] in (8, 16, 32):
            return RuleBinding({"n": region[0], "coefs": region[1]})
        return None


class ButterflyQuarterRewrite(RewriteRule):
    id = "butterfly-quarter"
    phase = "fuse-quarter"
    effect = "lo/hi split + O/EO/EE dataflow + three output families"
    measure = "sdot/mul family count per 4-row group"

    def preconditions(self, region, bindings):
        return bindings.values["n"] in (8, 16, 32)

    def apply(self, region, bindings):
        return region, _obligations(region[0])

    def fallback(self, region):
        return region


class ButterflyQuarterTemplate(CoverTemplate):
    id = "butterfly-quarter"
    target = "sve1|sve2"

    def preconditions(self, region, bindings):
        return ButterflyQuarterRewrite().preconditions(region, bindings)

    def emit(self, region, bindings, target="") -> Tuple[str,
                                                          List[ProofObligation]]:
        n = bindings.values["n"]
        return emit_quarter_pass(n=n, target=target or "sve2"), \
            _obligations(n)
