"""SATD 8x8 pure-SVE emitter (zero NEON, any VL).

Same width-independent DAG as optimizer/ir/satd8_op_ir.satd8_dag()
(load_diff -> hadamard_4_v -> transpose+abs/abd -> max/add ->
vpaddl/vpadal/vaddv), lowered to SVE2 ACLE only:
  - u8 loads  : svld1_u8 (SV_VL8) + svunpklo_u16 widening
  - 16-bit trn: svtbl2_s16 with fixed 8-lane index vectors (SVE TRN
    semantics differ from NEON TRN, so explicit lane tables are used)
  - 32-bit trn: svtbl2_s32 on the 4-lane s32 view (SV_VL4)
  - abs/abd   : svabs_s16_x / svabd_s16_x
  - reduce    : svuzp1/2_u16 pairwise + svunpklo_u32 + pairwise
    uzp adds + svlasta (no svaddv: GCC lowers it to NEON uaddv)
The SVE path keeps 8 active lanes at any VL.  Compile with
-march=armv8.2-a+sve2 (NO -msve-vector-bits=128: it constant-folds
svcntb() and dead-codes the fallback).  The runtime svcntb()==16 guard
calls an exact scalar transcription (marked no-tree-vectorize so GCC
cannot reintroduce NEON ops) on other vector lengths.
Validation: tools/test_satd8_pure_sve.py (0 NEON + numeric equality vs
the NEON DAG emitter under QEMU VL=128 and VL=256).
"""


def emit_satd8_pure_sve(func_name="dynopt_satd_8x8_pure_sve"):
    body = r"""\
// Generated by optimizer/ir/satd8_pure_sve_emit.py -- do not edit.
// SATD 8x8 pure SVE2 (zero NEON, any VL).
#include <arm_sve.h>
#include <stdint.h>

static __attribute__((noinline, optimize("no-tree-vectorize")))
int satd8_scalar_fallback(const uint8_t* pix1, intptr_t sp1,
                          const uint8_t* pix2, intptr_t sp2)
{
    // Exact scalar transcription of the two-quad algorithm (vertical
    // 4-point per 4-row group, horizontal 4-point with abs, max across
    // groups, pairwise reduce) so any VL gets the same integer result.
    int16_t d[8][8];
    for (int y = 0; y < 8; y++)
        for (int x = 0; x < 8; x++)
            d[y][x] = (int16_t)((int)pix1[y * sp1 + x] -
                                pix2[y * sp2 + x]);
    int16_t t[8][8];
    for (int g = 0; g < 2; g++)
        for (int c = 0; c < 8; c++)
        {
            int16_t r0 = d[4 * g + 0][c], r1 = d[4 * g + 1][c];
            int16_t r2 = d[4 * g + 2][c], r3 = d[4 * g + 3][c];
            int16_t s0 = r0 + r1, q0 = r0 - r1;
            int16_t s1 = r2 + r3, q1 = r2 - r3;
            t[4 * g + 0][c] = s0 + s1;
            t[4 * g + 2][c] = s0 - s1;
            t[4 * g + 1][c] = q0 + q1;
            t[4 * g + 3][c] = q0 - q1;
        }
    int16_t h[8][8];
    for (int g = 0; g < 2; g++)
    {
        int16_t s0[8], s1[8], da[8], db[8];
        for (int i = 0; i < 4; i++)
        {
            int16_t a = t[4 * g + 0][2 * i];
            int16_t b = t[4 * g + 0][2 * i + 1];
            int16_t c = t[4 * g + 1][2 * i];
            int16_t dd = t[4 * g + 1][2 * i + 1];
            int16_t e = t[4 * g + 2][2 * i];
            int16_t f = t[4 * g + 2][2 * i + 1];
            int16_t gg = t[4 * g + 3][2 * i];
            int16_t hh = t[4 * g + 3][2 * i + 1];
            int16_t sa = a + b, sb = c + dd;
            int16_t sc = e + f, sd = gg + hh;
            int16_t ad = a - b, bd = c - dd;
            int16_t cd = e - f, dd2 = gg - hh;
            s0[2 * i] = sa < 0 ? -sa : sa;
            s0[2 * i + 1] = sb < 0 ? -sb : sb;
            s1[2 * i] = sc < 0 ? -sc : sc;
            s1[2 * i + 1] = sd < 0 ? -sd : sd;
            da[2 * i] = ad < 0 ? -ad : ad;
            da[2 * i + 1] = bd < 0 ? -bd : bd;
            db[2 * i] = cd < 0 ? -cd : cd;
            db[2 * i + 1] = dd2 < 0 ? -dd2 : dd2;
        }
        h[4 * g + 0][0] = s0[0]; h[4 * g + 0][1] = s0[1];
        h[4 * g + 0][2] = s1[0]; h[4 * g + 0][3] = s1[1];
        h[4 * g + 0][4] = s0[4]; h[4 * g + 0][5] = s0[5];
        h[4 * g + 0][6] = s1[4]; h[4 * g + 0][7] = s1[5];
        h[4 * g + 1][0] = s0[2]; h[4 * g + 1][1] = s0[3];
        h[4 * g + 1][2] = s1[2]; h[4 * g + 1][3] = s1[3];
        h[4 * g + 1][4] = s0[6]; h[4 * g + 1][5] = s0[7];
        h[4 * g + 1][6] = s1[6]; h[4 * g + 1][7] = s1[7];
        h[4 * g + 2][0] = da[0]; h[4 * g + 2][1] = da[1];
        h[4 * g + 2][2] = db[0]; h[4 * g + 2][3] = db[1];
        h[4 * g + 2][4] = da[4]; h[4 * g + 2][5] = da[5];
        h[4 * g + 2][6] = db[4]; h[4 * g + 2][7] = db[5];
        h[4 * g + 3][0] = da[2]; h[4 * g + 3][1] = da[3];
        h[4 * g + 3][2] = db[2]; h[4 * g + 3][3] = db[3];
        h[4 * g + 3][4] = da[6]; h[4 * g + 3][5] = da[7];
        h[4 * g + 3][6] = db[6]; h[4 * g + 3][7] = db[7];
    }
    int satd = 0;
    for (int i = 0; i < 8; i++)
    {
        int16_t m0 = h[0][i] > h[1][i] ? h[0][i] : h[1][i];
        int16_t m1 = h[2][i] > h[3][i] ? h[2][i] : h[3][i];
        int16_t m2 = h[4][i] > h[5][i] ? h[4][i] : h[5][i];
        int16_t m3 = h[6][i] > h[7][i] ? h[6][i] : h[7][i];
        satd += m0 + m1 + m2 + m3;
    }
    return satd;
}

extern "C" int __FUNC__(const uint8_t* pix1, intptr_t sp1,
                        const uint8_t* pix2, intptr_t sp2)
{
    if (svcntb() != 16)
        return satd8_scalar_fallback(pix1, sp1, pix2, sp2);

    const svbool_t pg8b = svptrue_pat_b8(SV_VL8);
    const svbool_t pg8h = svptrue_pat_b16(SV_VL8);
    const svbool_t pg4s = svptrue_pat_b32(SV_VL4);
    const svbool_t pg2s = svptrue_pat_b32(SV_VL2);

    // diff rows: u8 -> s16 (zero-extend both, subtract).
#define LOAD_DIFF(i)                                                        \
    svreinterpret_s16_u16(svsub_u16_x(                                       \
        pg8h, svunpklo_u16(svld1_u8(pg8b, pix1 + (i) * sp1)),                \
        svunpklo_u16(svld1_u8(pg8b, pix2 + (i) * sp2))))
    svint16_t d0 = LOAD_DIFF(0), d1 = LOAD_DIFF(1), d2 = LOAD_DIFF(2);
    svint16_t d3 = LOAD_DIFF(3), d4 = LOAD_DIFF(4), d5 = LOAD_DIFF(5);
    svint16_t d6 = LOAD_DIFF(6), d7 = LOAD_DIFF(7);
#undef LOAD_DIFF

    // hadamard_4_v over rows 0..3 and 4..7.
#define H4(a, b, c, d)                                                      \
    do                                                                      \
    {                                                                       \
        svint16_t s0 = svadd_s16_x(pg8h, a, b);                             \
        svint16_t q0 = svsub_s16_x(pg8h, a, b);                             \
        svint16_t s1 = svadd_s16_x(pg8h, c, d);                             \
        svint16_t q1 = svsub_s16_x(pg8h, c, d);                             \
        svint16_t o0 = svadd_s16_x(pg8h, s0, s1);                           \
        svint16_t o2 = svsub_s16_x(pg8h, s0, s1);                           \
        svint16_t o1 = svadd_s16_x(pg8h, q0, q1);                           \
        svint16_t o3 = svsub_s16_x(pg8h, q0, q1);                           \
        a = o0; b = o1; c = o2; d = o3;                                     \
    } while (0)
    H4(d0, d1, d2, d3);
    H4(d4, d5, d6, d7);
#undef H4

    // 16-bit trn1/trn2 via tbl2 (NEON semantics: even/odd interleave).
    static const uint16_t trn1_16[8] = {0, 8, 2, 10, 4, 12, 6, 14};
    static const uint16_t trn2_16[8] = {1, 9, 3, 11, 5, 13, 7, 15};
    const svuint16_t i_trn1_16 = svld1_u16(pg8h, trn1_16);
    const svuint16_t i_trn2_16 = svld1_u16(pg8h, trn2_16);
    static const uint32_t trn1_32[4] = {0, 4, 2, 6};
    static const uint32_t trn2_32[4] = {1, 5, 3, 7};
    const svuint32_t i_trn1_32 = svld1_u32(pg4s, trn1_32);
    const svuint32_t i_trn2_32 = svld1_u32(pg4s, trn2_32);

#define HABS(in0, in1, in2, in3, o0, o1, o2, o3)                            \
    do                                                                      \
    {                                                                       \
        svint16_t t0 = svtbl2_s16(                                          \
            svcreate2_s16(in0, in1), i_trn1_16);                            \
        svint16_t t1 = svtbl2_s16(                                          \
            svcreate2_s16(in0, in1), i_trn2_16);                            \
        svint16_t t2 = svtbl2_s16(                                          \
            svcreate2_s16(in2, in3), i_trn1_16);                            \
        svint16_t t3 = svtbl2_s16(                                          \
            svcreate2_s16(in2, in3), i_trn2_16);                            \
        svint16_t sa = svadd_s16_x(pg8h, t0, t1);                           \
        svint16_t da = svabd_s16_x(pg8h, t0, t1);                           \
        svint16_t sb = svadd_s16_x(pg8h, t2, t3);                           \
        svint16_t db = svabd_s16_x(pg8h, t2, t3);                           \
        svint16_t s0 = svabs_s16_x(pg8h, sa);                               \
        svint16_t s1 = svabs_s16_x(pg8h, sb);                               \
        svint32_t a32 = svreinterpret_s32_s16(s0);                          \
        svint32_t b32 = svreinterpret_s32_s16(s1);                          \
        svint32_t c32 = svreinterpret_s32_s16(da);                          \
        svint32_t d32 = svreinterpret_s32_s16(db);                          \
        o0 = svreinterpret_s16_s32(svtbl2_s32(                              \
            svcreate2_s32(a32, b32), i_trn1_32));                           \
        o1 = svreinterpret_s16_s32(svtbl2_s32(                              \
            svcreate2_s32(a32, b32), i_trn2_32));                           \
        o2 = svreinterpret_s16_s32(svtbl2_s32(                              \
            svcreate2_s32(c32, d32), i_trn1_32));                           \
        o3 = svreinterpret_s16_s32(svtbl2_s32(                              \
            svcreate2_s32(c32, d32), i_trn2_32));                           \
    } while (0)
    svint16_t h0, h1, h2, h3, h4, h5, h6, h7;
    HABS(d0, d1, d2, d3, h0, h1, h2, h3);
    HABS(d4, d5, d6, d7, h4, h5, h6, h7);
#undef HABS

    svuint16_t m0 = svmax_u16_x(pg8h, svreinterpret_u16_s16(h0),
                                svreinterpret_u16_s16(h1));
    svuint16_t m1 = svmax_u16_x(pg8h, svreinterpret_u16_s16(h2),
                                svreinterpret_u16_s16(h3));
    svuint16_t m2 = svmax_u16_x(pg8h, svreinterpret_u16_s16(h4),
                                svreinterpret_u16_s16(h5));
    svuint16_t m3 = svmax_u16_x(pg8h, svreinterpret_u16_s16(h6),
                                svreinterpret_u16_s16(h7));
    svuint16_t o0 = svadd_u16_x(pg8h, m0, m1);
    svuint16_t o1 = svadd_u16_x(pg8h, m2, m3);

    // reduce: pairwise u16 sums -> u32 -> total via uzp adds + SVE
    // LASTA (svaddv lowers to NEON uaddv and svlasta to NEON mov, so
    // both are emitted via inline asm / avoided).
    svuint16_t p0x = svadd_u16_x(pg8h, svuzp1_u16(o0, o0),
                                 svuzp2_u16(o0, o0));
    svuint16_t p1x = svadd_u16_x(pg8h, svuzp1_u16(o1, o1),
                                 svuzp2_u16(o1, o1));
    svuint32_t s0 = svunpklo_u32(p0x);
    svuint32_t s1 = svadd_u32_x(pg4s, s0, svunpklo_u32(p1x));
    svuint32_t p1 = svadd_u32_x(pg2s, svuzp1_u32(s1, s1),
                                svuzp2_u32(s1, s1));
    svuint32_t p2 = svadd_u32_x(pg2s, svuzp1_u32(p1, p1),
                                svuzp2_u32(p1, p1));
    uint32_t total;
    __asm__("lasta %w0, %1, %2.s"
            : "=r"(total)
            : "Upl"(pg2s), "w"(p2));
    return (int)total;
}
"""
    return body.replace("__FUNC__", func_name)
