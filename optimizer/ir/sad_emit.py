"""SAD 16x16 DAG -> pure-NEON ACLE emitter (asm-family PoC)."""

from __future__ import annotations

from typing import List

from op_ir import Op


def emit_sad16(ops, func_name: str = "dynopt_sad_16x16_sve2") -> str:
    body: List[str] = []
    ret = "sad"
    for op in ops:
        kind = op.kind
        attrs = op.attrs
        out = op.out
        ins = list(op.inputs)
        if kind == "dup16":
            body.append("    uint16x8_t %s = vdupq_n_u16(%d);"
                        % (out, attrs["value"]))
        elif kind == "load_u8x16":
            sv = "stride1" if attrs["base"] == "pix1" else "stride2"
            body.append("    uint8x16_t %s = vld1q_u8(%s + %d * %s);"
                        % (out, attrs["base"], attrs["row"], sv))
        elif kind == "vget":
            fn = "vget_low_u8" if attrs["which"] == "lo" else "vget_high_u8"
            body.append("    uint8x8_t %s = %s(%s);" % (out, fn, ins[0]))
        elif kind == "vabal":
            body.append("    uint16x8_t %s = vabal_u8(%s, %s, %s);"
                        % (out, ins[0], ins[1], ins[2]))
        elif kind == "vaddlv":
            body.append("    int %s = (int)vaddlvq_u16(%s);"
                        % (out, ins[0]))
        elif kind == "scalar_add2":
            body.append("    int %s = %s + %s;" % (ret, ins[0], ins[1]))
        else:
            raise ValueError("sad emit: %s" % kind)
    return """\
// Generated by optimizer/ir/sad_emit.py -- do not edit by hand.
// SAD 16x16 pure NEON from width-independent DAG.
#include <arm_neon.h>
#include <stdint.h>

extern "C" int %s(const uint8_t* pix1, intptr_t stride1,
                  const uint8_t* pix2, intptr_t stride2)
{
%s
    return %s;
}
""" % (func_name, "\n".join(body), ret)
