"""MC avg_pp 16x16 DAG -> pure-NEON ACLE emitter."""

from __future__ import annotations

from typing import List

from op_ir import Op


def emit_avg_pp(ops, func_name: str = "dynopt_avg_pp_16x16_sve2") -> str:
    body: List[str] = []
    for op in ops:
        kind = op.kind
        attrs = op.attrs
        out = op.out
        ins = list(op.inputs)
        if kind == "load_u8x16":
            sv = "stride1" if attrs["base"] == "pix1" else "stride2"
            body.append("    uint8x16_t %s = vld1q_u8(%s + %d * %s);"
                        % (out, attrs["base"], attrs["row"], sv))
        elif kind == "rhadd":
            body.append("    uint8x16_t %s = vrhaddq_u8(%s, %s);"
                        % (out, ins[0], ins[1]))
        elif kind == "store_u8x16":
            body.append("    vst1q_u8(dst + %d * dstStride, %s);"
                        % (attrs["row"], ins[0]))
        else:
            raise ValueError("avg emit: %s" % kind)
    return """\
// Generated by optimizer/ir/mc_avg_emit.py -- do not edit by hand.
// MC avg_pp 16x16 pure NEON from width-independent DAG.
#include <arm_neon.h>
#include <stdint.h>

extern "C" void %s(uint8_t* dst, intptr_t dstStride,
                   const uint8_t* pix1, intptr_t stride1,
                   const uint8_t* pix2, intptr_t stride2)
{
%s
}
""" % (func_name, "\n".join(body))
