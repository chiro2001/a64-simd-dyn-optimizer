#!/usr/bin/env python3
"""Generate C++ NEON intrinsics roundtrip from imported MachineIR.

Usage: python3 kernels/sa8d/gen_roundtrip.py <machine-ir.json> <out.cpp>
"""

import json
import sys

from optimizer.ir.codegen import emit_c_intrinsics


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    with open(sys.argv[1]) as f:
        doc = json.load(f)
    from optimizer.ir.machine_ir import MachineIR
    ir = MachineIR(function=doc["function"], nodes=doc["nodes"])
    src = emit_c_intrinsics(ir)
    with open(sys.argv[2], "w") as f:
        f.write("// generated by kernels/sa8d/gen_roundtrip.py; do not edit\n")
        f.write(src)
    print("wrote %s (%d lines)" % (sys.argv[2], src.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
